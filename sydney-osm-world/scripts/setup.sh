#!/usr/bin/env bash
# One-shot setup for the Sydney OSM world pipeline.
#
#   bash scripts/setup.sh
#
# Safe to re-run. Requires: git, and `uv` (https://docs.astral.sh/uv/).
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$(pwd)"
echo "==> project root: $ROOT"

# ---------------------------------------------------------------- MCP server
if [ ! -d open-streetmap-mcp/.git ]; then
  echo "==> cloning the OSM MCP server"
  git clone https://github.com/jagan-shanmugam/open-streetmap-mcp.git open-streetmap-mcp
else
  echo "==> open-streetmap-mcp already present"
fi

PATCH="patches/open-streetmap-mcp-useragent-and-subcategory.patch"
if [ -f "$PATCH" ]; then
  echo "==> applying local patch to the MCP server"
  (
    cd open-streetmap-mcp
    if git apply --check "$ROOT/$PATCH" 2>/dev/null; then
      git apply "$ROOT/$PATCH" && echo "    patch applied"
    elif git apply --reverse --check "$ROOT/$PATCH" 2>/dev/null; then
      echo "    already applied - skipping"
    else
      echo "    WARNING: patch does not apply and is not already applied."
      echo "    The MCP server will likely fail at runtime. See docs/OSM-MCP.md."
    fi
  )
fi

# ----------------------------------------------------------------- python env
# The MCP server declares requires-python >= 3.13, so the venv must be 3.13+.
if ! command -v uv >/dev/null 2>&1; then
  echo "ERROR: 'uv' is required. Install it:  https://docs.astral.sh/uv/getting-started/installation/" >&2
  exit 1
fi

if [ ! -d .venv ]; then
  echo "==> creating Python 3.13 venv"
  uv venv --python 3.13 .venv
fi

if [ -x .venv/bin/python ]; then PY=".venv/bin/python"; else PY=".venv/Scripts/python.exe"; fi

echo "==> installing dependencies (mcp pinned <2 - see docs/OSM-MCP.md)"
uv pip install --python "$PY" -r requirements.txt
uv pip install --python "$PY" -e ./open-streetmap-mcp

echo "==> verifying the MCP server imports"
"$PY" -c "import osm_mcp_server; from importlib.metadata import version; print('   osm_mcp_server imports OK (mcp', version('mcp') + ')')"

# The uv-managed CPython ships a CA store whose Let's Encrypt chain has expired.
# Point every OSM HTTPS call at the certifi bundle instead. See docs/OSM-MCP.md.
CERT="$("$PY" -c 'import certifi; print(certifi.where())')"
echo "==> SSL_CERT_FILE=$CERT"

cat > .env.local <<EOF
# Generated by scripts/setup.sh - source this before running the pipeline.
export SSL_CERT_FILE="$CERT"
export PY="$PY"
EOF

mkdir -p data/raw data/normalized data/world world docs data/cache

echo
echo "Setup complete. Next:"
echo "  source .env.local"
echo "  bash scripts/run_all.sh"
